#!/usr/bin/env python3
"""Expose module JSON UI text to Qt lupdate, without changing IDs or settings."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'i18n' / 'ManifestStrings.h'

def generate():
    lines = ['// Generated by scripts/update-manifest-translations.py; do not edit.',
             '// Extraction only. JSON IDs, option values and defaults remain untranslated.',
             '#pragma once', '#include <QtCore/QCoreApplication>', '']
    for manifest in sorted((ROOT / 'modules').glob('*/manifest.json')):
        data = json.loads(manifest.read_text())
        strings = {data['name']}
        for setting in data.get('settings', []):
            for key in ('label', 'description'):
                if setting.get(key): strings.add(setting[key])
            for value in setting.get('options', []):
                if isinstance(value, str): strings.add(value)
        lines.append('// ' + manifest.relative_to(ROOT).as_posix())
        for index, value in enumerate(sorted(strings)):
            identifier = manifest.parent.name + '_' + str(index)
            lines.append('inline const char *const ' + identifier + ' = QT_TRANSLATE_NOOP(' +
                         json.dumps(data['id']) + ', ' + json.dumps(value, ensure_ascii=False) + ');')
        lines.append('')
    return '\n'.join(lines)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit('Manifest translation strings are stale. Run scripts/update-manifest-translations.py')
    else:
        TARGET.write_text(content)
    # mpv UI strings share one catalog context, regardless of which OSC uses them.
    import re
    words = set()
    for path in (ROOT / 'scripts').glob('mpv-*.lua'):
        for literal in re.findall(r'\bT\(("(?:[^"\\]|\\.)*")\)', path.read_text()):
            words.add(json.loads(literal))
    mpv = ['// Generated by scripts/update-manifest-translations.py; do not edit.',
           '#pragma once', '#include <QtCore/QCoreApplication>',
           'inline const char *const mpvSourceStrings[] = {']
    mpv += ['    QT_TRANSLATE_NOOP("MpvOsd", ' + json.dumps(word) + '),' for word in sorted(words)]
    mpv += ['};', '']
    target = ROOT / 'i18n' / 'MpvStrings.h'
    data = '\n'.join(mpv)
    if args.check:
        if not target.exists() or target.read_text() != data:
            raise SystemExit('mpv translation strings are stale. Run scripts/update-manifest-translations.py')
    else:
        target.write_text(data)
